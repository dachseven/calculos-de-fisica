public class Vector{
    public double i;
    public double j;
    public double k;
    Vector(double i,double j, double k){
        this.i=i;
        this.j=j;
        this.k=k;
    }
    public double geti(){
        return i;
    }
public double getj(){
        return j;
    }
    public double getk(){
        return k;
    }
}